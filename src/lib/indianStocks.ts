export function buildReferenceQuote(entry: IndianStockDirectoryEntry, timestamp: string): MarketQuote {
  const change = Number((entry.refPrice - entry.refPrevClose).toFixed(2));
  const changePercent = Number(((change / entry.refPrevClose) * 100).toFixed(2));
  return {
    symbol: entry.symbol,
    name: entry.name,
    exchange: entry.exchange,
    sector: entry.sector,
    price: entry.refPrice,
    previousClose: entry.refPrevClose,
    change,
    changePercent,
    dayHigh: entry.refHigh,
    dayLow: entry.refLow,
    open: entry.refPrevClose,
    volume: entry.refVolume,
    marketCap: entry.refMarketCapCr * 1e7,
    week52High: entry.ref52WHigh,
    week52Low: entry.ref52WLow,
    source: 'reference-snapshot',
    lastUpdated: timestamp,
  };
}

export function buildReferenceIndex(
  idx: (typeof INDIAN_INDICES_REF)[number],
  timestamp: string
): IndexOverview {
  const change = Number((idx.refPrice - idx.refPrevClose).toFixed(2));
  const changePercent = Number(((change / idx.refPrevClose) * 100).toFixed(2));
  return {
    symbol: idx.symbol,
    name: idx.name,
    price: idx.refPrice,
    change,
    changePercent,
    dayHigh: idx.refHigh,
    dayLow: idx.refLow,
    source: 'reference-snapshot',
    lastUpdated: timestamp,
  };
}
